import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1366, height: 657 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://localhost:4173/git-lab/', { waitUntil: 'networkidle0' });
await page.evaluate(() => navigator.serviceWorker.ready.then(() => true));
await new Promise(r => setTimeout(r, 1500));
await page.setOfflineMode(true);
const requests = [];
page.on('request', r => { if (!r.url().startsWith('http://localhost')) requests.push(r.url()); });
await page.reload({ waitUntil: 'load' });
await page.waitForSelector('.xterm-helper-textarea', { timeout: 15000 });
await page.focus('.xterm-helper-textarea');
await page.keyboard.type('git init'); await page.keyboard.press('Enter');
await new Promise(r => setTimeout(r, 800));
await page.click('[data-path="/project/index.html"]');
await new Promise(r => setTimeout(r, 800));
console.log('offline reload ok, strip:', await page.$eval('#state-strip', e => e.textContent));
console.log('monaco loaded offline:', !!(await page.$('.monaco-editor .view-lines')));
console.log('external requests:', requests.length ? requests : 'none');
console.log(errors.length ? errors : 'no errors');
await browser.close();
