// New File button: create a file, reject a duplicate name, and check Git sees the file.
import puppeteer from 'puppeteer-core';
const base = process.argv[2] || 'http://localhost:5173/';
const shot = process.argv[3];
const b = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const p = await b.newPage();
await p.setViewport({ width: 1366, height: 657 });
const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.goto(base, { waitUntil: 'networkidle0', timeout: 60000 });
await p.waitForSelector('.xterm-helper-textarea');
const wait = ms => new Promise(r => setTimeout(r, ms));
const run = async l => { await p.focus('.xterm-helper-textarea'); await p.keyboard.type(l); await p.keyboard.press('Enter'); await wait(800); };
await run('git init');
await p.click('#btn-new-file'); await wait(400);
await p.keyboard.type('notes.txt'); await p.keyboard.press('Enter'); await wait(1200);
console.log('in tree:', !!(await p.$('[data-path="/project/notes.txt"]')), '| open tab:', await p.$eval('.tab.active', e => e.textContent.trim()));
await p.click('#btn-new-file'); await wait(400);
await p.keyboard.type('index.html'); await p.keyboard.press('Enter'); await wait(500);
console.log('duplicate message:', await p.$eval('.tree-msg', e => e.hidden ? '(hidden)' : e.textContent).catch(() => 'none'));
if (shot) await p.screenshot({ path: shot });
await p.keyboard.press('Escape'); await wait(300);
console.log('box gone after Esc:', !(await p.$('.tree-input')));
await p.click('#btn-new-file'); await wait(400);
await p.keyboard.type('css/theme.css'); await p.keyboard.press('Enter'); await wait(1200);
console.log('nested file:', !!(await p.$('[data-path="/project/css/theme.css"]')));
await run('clear'); await run('git status');
const out = await p.$eval('.xterm-rows', e => e.innerText);
console.log(out.split('\n').filter(l => /untracked|notes|css|Untracked/.test(l)).join('\n'));
console.log('strip:', await p.$eval('#state-strip', e => e.textContent));
console.log(errs.length ? errs : 'no errors');
await b.close();
