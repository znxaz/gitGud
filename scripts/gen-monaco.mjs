// Builds src/ui/monaco-entry.js from monaco's own editor.main.js,
// keeping every editor feature but only the languages this lab needs.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('node_modules/monaco-editor/esm/vs/editor/editor.main.js', 'utf8');
const keep = src.split('\n').filter(l =>
  l.trim() &&
  !l.includes('monaco-lsp-client') &&
  !l.includes('as lsp') &&
  !l.includes('languages/definitions/') &&
  !l.includes('languages/features/') &&
  !l.includes('__src_languages_features'));
const fix = l => l.replace(/from '\.\.\//g, "from 'monaco-esm/").replace(/from '\.\//g, "from 'monaco-esm/editor/")
  .replace(/import '\.\.\//g, "import 'monaco-esm/").replace(/import '\.\//g, "import 'monaco-esm/editor/");
const langs = ['html', 'css', 'javascript', 'markdown', 'ini'].map(l => `import 'monaco-esm/languages/definitions/${l}/register.js';`);
writeFileSync('src/ui/monaco-entry.js', '// Generated by scripts/gen-monaco.mjs\n' + [...langs, ...keep.map(fix)].join('\n') + '\n');
console.log('lines', keep.length);
